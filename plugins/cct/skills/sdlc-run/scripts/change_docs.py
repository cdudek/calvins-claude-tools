def _used_re(fams) -> re.Pattern:
    return re.compile(rf"(?<![\w@/.#-])([{''.join(fams)}])(\d{{1,3}})\b")


MEANING = 100
MARKER = "<!-- generated by sdlc_status.py readme -->"


def _md_files(change: Path) -> list[Path]:
    return [p for p in sorted(change.rglob("*.md")) if p.name != "README.md"]


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def _first_sentence(text: str) -> str:
    text = re.sub(r"\*\*|`", "", text).strip(" :-—")
    first = re.split(r"(?<=[.?!])\s", text, maxsplit=1)[0].strip()
    if len(first) > MEANING:
        first = first[:MEANING].rsplit(" ", 1)[0] + "..."
    return first


def meaning(ident: str, line: str, header: list[str] | None = None) -> str | None:
    """The one-line meaning when `line` defines `ident`, else None. A definition is a table row
    whose first cell is the id, or a list item that opens with the id (bold or not)."""
    if line.lstrip().startswith("|"):
        cells = _cells(line)
        if cells[0] != ident or len(cells) < 2:
            return None
        if ident[0] == "A" and len(cells) > 3:
            return _first_sentence(cells[3])
        if ident[0] == "J" and len(cells) > 3:
            return _first_sentence(f"When {cells[1]}, I want {cells[2]}, so I can {cells[3]}")
        if ident[0] in "XH" and header:  # the Finding or Challenge column, not the longest cell
            col = next(
                (i for i, h in enumerate(header) if h.lower() in ("finding", "challenge")), -1
            )
            if 0 < col < len(cells):
                return _first_sentence(cells[col])
        return _first_sentence(max(cells[1:], key=len))
    m = re.match(rf"^\s*(?:[-*]|\d+\.)\s+(?:\[[ x]\]\s+)?\**{ident}\b(.*)$", line)
    if not m:
        return None
    rest = re.sub(r"^\**\s*(?:\([^)]*\)\s*)*", "", m.group(1))  # drop "** (A1; rules x)" lead
    return _first_sentence(rest) or None


def _lines(text: str):
    """(line, header cells of the table it sits in, or None)."""
    lines, header = text.splitlines(), None
    for i, line in enumerate(lines):
        if not line.lstrip().startswith("|"):
            header = None
        elif i + 1 < len(lines) and re.fullmatch(r"\s*\|[\s:|-]+\|\s*", lines[i + 1]):
            header = _cells(line)
        yield line, header


def ids(change: Path) -> list[str]:
    """One line per id the change defines, `F1  <meaning>  (facts.md)`, then the ids it only uses.
    In layout 4 `R` is a rule (read from its rule file) and a review finding is `V`."""
    fams = spec.id_families(change)
    files = _md_files(change)
    used = {
        m.group(0)
        for p in files
        for m in _used_re(fams).finditer(
            re.sub(r"```.*?```", "", p.read_text(encoding="utf-8"), flags=re.S)
        )
    }
    rules = {}
    if fams is spec.FAMILIES_V4:
        rules = {r.id: r for r in spec.load_rules(change.parent.parent)[0]}
    found: dict[str, tuple[str, str]] = {}
    for ident in sorted(used, key=lambda i: (list(fams).index(i[0]), int(i[1:]))):
        if ident in rules:
            found[ident] = (rules[ident].summary or rules[ident].body, rules[ident].path)
            continue
        home = fams[ident[0]][1]
        order = [p for p in files if p.name == home] + [p for p in files if p.name != home]
        for p in order:
            hit = next(
                (
                    t
                    for line, header in _lines(p.read_text(encoding="utf-8"))
                    if (t := meaning(ident, line, header))
                ),
                None,
            )
            if hit:
                found[ident] = (hit, str(p.relative_to(change)))
                break
    out = [f"{i:<5}{text}  ({where})" for i, (text, where) in found.items()]
    missing = sorted((i for i in used if i not in found), key=lambda i: (i[0], int(i[1:])))
    if missing:
        out.append(f"no definition found for: {', '.join(missing)}")
    return out or ["no ids in this change yet"]


