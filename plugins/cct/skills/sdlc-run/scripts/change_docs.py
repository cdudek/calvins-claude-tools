LEGACY = {"spec/readiness.md": "spec/validation.md"}  # written before the rename


def _ignored(change: Path, rel: str) -> bool:
    """Git ignores this path (the gate's verify/ folder, scratch): a README link to it fails in a clean checkout."""
    if rel.split("/")[0] == "verify":
        return True
    try:
        return subprocess.run(["git", "-C", str(change), "check-ignore", "-q", "--", rel], capture_output=True).returncode == 0
    except OSError:
        return False


def _name(change: Path, rel: str) -> str:
    if not (change / rel).exists() and (change / LEGACY.get(rel, rel)).exists():
        rel = LEGACY[rel]
    if not (change / rel).exists():
        return f"{rel} (not written yet)"
    return rel if _ignored(change, rel) else f"[{rel}]({rel})"  # never link an ignored path


def latest_handover(change: Path) -> Path | None:
    """The newest handover*.md: by the date in its name, else by its number (handover-10 after
    handover-9), else the plain handover.md last of all. Names, not file times: a checkout resets those."""

    def key(p: Path) -> tuple[str, int, str]:
        stem = p.stem
        date = re.search(r"\d{4}-\d{2}-\d{2}", stem)
        nums = re.findall(r"(?<!\d)\d+(?!\d)", re.sub(r"\d{4}-\d{2}-\d{2}", "", stem))
        return (date.group(0) if date else "", int(nums[-1]) if nums else 0, p.name)

    found = sorted(change.glob("handover*.md"), key=key)
    return found[-1] if found else None


KNOWN_DIRS = ("verify", "asks", "spec/prototype")


def others(change: Path) -> list[str]:
    """Files in the folder (two levels deep) that neither table names."""
    known = {f for f, *_ in DOCS} | {f for f, *_ in FOR_AGENTS} | {"README.md", *LEGACY.values()}
    out = []
    for p in sorted(change.rglob("*")):
        rel = p.relative_to(change).as_posix()
        if not p.is_file() or len(p.relative_to(change).parts) > 2 or rel in known:
            continue
        if (
            p.name.startswith(".")
            or p.name.startswith("handover")
            or rel.startswith(tuple(f"{d}/" for d in KNOWN_DIRS))
            or _ignored(change, rel)
        ):
            continue
        out.append(rel)
    return out


def readme(change: Path, stage: str) -> str:
    """The reading map of one change folder; regenerated, never edited by hand."""
    latest = latest_handover(change)
    pick = f"[{latest.name}]({latest.name})" if latest else "no handover yet"
    out = [
        f"# {change.name}",
        "",
        MARKER,
        "",
        "GENERATED by `sdlc_status.py readme`; do not edit by hand. Ids such as F1 or Q3 are "
        f"explained by `sdlc_status.py ids {change.name}`.",
        "",
        "## Start here",
        "",
        f"- **Understand the change:** read {_name(change, 'intent.md')}.",
        f"- **Review it:** read {_name(change, 'facts.md')}, then {_name(change, 'plan.md')}.",
        f"- **Pick up the work:** the change is at stage {stage}; read {pick}.",
        "",
        "## What each document answers",
        "",
        "| Document | Question it answers | Who writes it | Stage | A newcomer needs it |",
        "|---|---|---|---|---|",
    ]
    shown = latest.name if latest else "handover.md"
    out += [
        f"| {_name(change, shown if f == 'handover.md' else f)} | {q} | {w} | {s} | {n} |"
        for f, q, w, s, n in DOCS
    ]
    out += [
        "",
        "## For agents",
        "",
        "Working files. A newcomer can skip all of them.",
        "",
        "| Document | Question it answers | Who writes it | Stage |",
        "|---|---|---|---|",
    ]
    out += [f"| {_name(change, f)} | {q} | {w} | {s} |" for f, q, w, s in FOR_AGENTS]
    if extra := others(change):
        out += ["", "## Other files in this folder", "", "Not in either list above.", ""]
        out += [f"- [{rel}]({rel})" for rel in extra]
    return "\n".join(out) + "\n"
